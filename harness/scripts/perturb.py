#!/usr/bin/env python3
from __future__ import annotations
import argparse
import json
import re
import sys
from pathlib import Path

DATASET = Path("datasets/miniF2F_v2c.json")
OUT_ROOT = Path("harness/problems_perturbed")

from build_problems import SUBSET_NAMES  # type: ignore

KINDS = ("alpha_rename", "hyp_reorder", "restate")

BARE_TEMPLATE = """-- Auto-generated by harness/scripts/perturb.py. Do not edit by hand.
-- Problem: {name}
-- Source: miniF2F-v2 (v2c, test split). Perturbation kind: {kind}.

{header}{formal_statement}
  sorry
"""

SUB_DIGITS = "₀₁₂₃₄₅₆₇₈₉"
SUB_TO_INT = {c: i for i, c in enumerate(SUB_DIGITS)}

def split_signature(stmt: str) -> tuple[str, list[str], str] | None:
    m = re.match(r"\s*theorem\s+(\S+)\s*", stmt)
    if not m:
        return None
    pos = m.end()
    binders: list[str] = []
    while pos < len(stmt) and stmt[pos] in "({[":
        open_c = stmt[pos]
        close_c = {"(": ")", "{": "}", "[": "]"}[open_c]
        depth = 0
        start = pos
        while pos < len(stmt):
            if stmt[pos] == open_c:
                depth += 1
            elif stmt[pos] == close_c:
                depth -= 1
                if depth == 0:
                    pos += 1
                    break
            pos += 1
        if depth != 0:
            return None
        binders.append(stmt[start:pos])
        while pos < len(stmt) and stmt[pos] in " \t\n":
            pos += 1
    prefix = stmt[: m.end()]
    rest = stmt[pos:]
    return prefix, binders, rest


def binder_idents(binder: str) -> list[str]:
    inner = binder[1:-1]
    head = inner.split(":", 1)[0].strip()
    return head.split()


def alpha_rename(name: str, header: str, stmt: str) -> tuple[str, str] | None:
    parts = split_signature(stmt)
    if parts is None:
        return None
    prefix, binders, rest = parts

    rename: dict[str, str] = {}

    h_label_re = re.compile(r"^(h|H)([0-9]|[₀-₉])$")
    next_idx = 0
    for binder in binders:
        for ident in binder_idents(binder):
            if h_label_re.match(ident) and ident not in rename:
                last = ident[-1]
                if last in SUB_DIGITS:
                    rename[ident] = "k" + SUB_DIGITS[next_idx]
                else:
                    rename[ident] = f"k{next_idx}"
                next_idx += 1

    if not rename:
        return None

    new_stmt = stmt
    for old, new in rename.items():
        pat = re.compile(
            r"(?<![A-Za-z0-9_'₀-₉])"
            + re.escape(old)
            + r"(?![A-Za-z0-9_'₀-₉])"
        )
        new_stmt = pat.sub(new, new_stmt)

    new_thm_name = name + "_ar"
    new_stmt = re.sub(
        r"\btheorem\s+" + re.escape(name) + r"\b",
        f"theorem {new_thm_name}",
        new_stmt,
        count=1,
    )
    return new_thm_name, new_stmt


def hyp_reorder(name: str, header: str, stmt: str) -> tuple[str, str] | None:
    parts = split_signature(stmt)
    if parts is None:
        return None
    prefix, binders, rest = parts

    is_hyp = [
        bool(binder_idents(b) and binder_idents(b)[0].lower().startswith("h"))
        for b in binders
    ]
    if sum(is_hyp) < 2:
        return None

    reversed_hyps = [binders[i] for i in range(len(binders)) if is_hyp[i]][::-1]
    out: list[str] = []
    hyp_iter = iter(reversed_hyps)
    for i, b in enumerate(binders):
        out.append(next(hyp_iter) if is_hyp[i] else b)

    new_stmt = prefix + " ".join(out) + rest
    return name, new_stmt


GOAL_RE = re.compile(r"\s*:\s*(?P<goal>.+?)\s*:=\s*by\s*\Z", re.DOTALL)


def restate(name: str, header: str, stmt: str) -> tuple[str, str] | None:
    m = GOAL_RE.search(stmt)
    if not m:
        return None
    goal = m.group("goal").strip()

    bad_tokens = ("∧", "∨", "↔", "∀", "∃", "→")
    if any(tok in goal for tok in bad_tokens):
        return None

    for op, swapped in [(" ≤ ", " ≥ "), (" < ", " > "),
                        (" ≥ ", " ≤ "), (" > ", " < ")]:
        if op in goal:
            if goal.count(op) != 1:
                return None
            lhs, rhs = goal.split(op)
            new_goal = rhs.strip() + swapped + lhs.strip()
            new_stmt = stmt[: m.start()] + f" : {new_goal} := by"
            return name, new_stmt

    if " = " in goal and goal.count(" = ") == 1:
        lhs, rhs = goal.split(" = ")
        new_goal = rhs.strip() + " = " + lhs.strip()
        new_stmt = stmt[: m.start()] + f" : {new_goal} := by"
        return name, new_stmt

    return None


TRANSFORMS = {
    "alpha_rename": alpha_rename,
    "hyp_reorder": hyp_reorder,
    "restate": restate,
}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--dataset", default=DATASET, type=Path)
    parser.add_argument("--out-root", default=OUT_ROOT, type=Path)
    parser.add_argument("--kind", choices=KINDS, action="append",
                        help="Which perturbation kinds to emit (repeatable; "
                             "default: all three).")
    parser.add_argument("--problem", action="append",
                        help="Restrict to specific problems (repeatable).")
    args = parser.parse_args()

    data = json.loads(args.dataset.read_text())
    by_name = {p["name"]: p for p in data if p["split"] == "test"}

    names = args.problem or SUBSET_NAMES
    missing = [n for n in names if n not in by_name]
    if missing:
        print(f"ERROR: dataset missing: {missing}", file=sys.stderr)
        return 1

    kinds = args.kind or list(KINDS)
    written = {k: 0 for k in kinds}
    skipped = {k: [] for k in kinds}

    for kind in kinds:
        out_dir = args.out_root / kind
        out_dir.mkdir(parents=True, exist_ok=True)
        for name in names:
            problem = by_name[name]
            result = TRANSFORMS[kind](name, problem["header"],
                                      problem["formal_statement"])
            if result is None:
                skipped[kind].append(name)
                continue
            _new_name, new_stmt = result
            (out_dir / f"{name}.lean").write_text(BARE_TEMPLATE.format(
                name=name, kind=kind, header=problem["header"],
                formal_statement=new_stmt,
            ))
            written[kind] += 1

    for kind in kinds:
        print(f"{kind}: wrote {written[kind]}, skipped {len(skipped[kind])}",
              file=sys.stderr)
        for n in skipped[kind]:
            print(f"  - {n} (no-op for {kind})", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
