CONTRIB_TEMPLATE = """-- Problem: {name}
-- Source: miniF2F-v2 (v2c, test split) — Ospanov et al. 2025
-- Stratum: {stratum_code}. {stratum_label}
-- Why this problem: {purpose}
--
-- Author: (your name here)
--
-- Rules (see ../README.md):
--   * Tactic mode only.
--   * No bare one-liner closer as the entire proof (decide / nlinarith /
--     polyrith / omega / aesop alone is not a valid submission unless this
--     header explicitly says otherwise).
--   * Do NOT modify the `theorem ... := by` line below — it is the v2c
--     statement verbatim. Only replace the `sorry` with your proof.
--
-- Informal statement:
{informal_comment}

{header}{formal_statement}
  sorry
"""

DEFAULT_OUT = {"bare": "harness/problems", "contributor": "human_baseline/problems"}

def load_dataset(path: Path) -> dict:
    data = json.loads(path.read_text())
    return {p["name"]: p for p in data if p["split"] == "test"}


def render(name: str, entry: dict, fmt: str) -> str:
    if fmt == "bare":
        return BARE_TEMPLATE.format(
            name=name, header=entry["header"],
            formal_statement=entry["formal_statement"],
        )
    sc, sl, purpose = RATIONALE[name]
    wrapped = textwrap.fill(
        entry["informal_statement"].strip(),
        width=78, initial_indent="--   ", subsequent_indent="--   ",
    )
    return CONTRIB_TEMPLATE.format(
        name=name, stratum_code=sc, stratum_label=sl, purpose=purpose,
        informal_comment=wrapped, header=entry["header"],
        formal_statement=entry["formal_statement"],
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dataset", default="datasets/miniF2F_v2c.json",
                        help="Path to v2c JSON (run fetch_dataset.py first).")
    parser.add_argument("--format", choices=("bare", "contributor"),
                        default="bare",
                        help="Template style (default: bare).")
    parser.add_argument("--out", default=None,
                        help="Output directory. Default depends on --format.")
    parser.add_argument("--all", action="store_true",
                        help="Build all 244 test-split problems (bare only).")
    args = parser.parse_args()

    if args.all and args.format == "contributor":
        print("ERROR: --all is incompatible with --format contributor "
              "(no per-problem rationale available outside the subset).",
              file=sys.stderr)
        return 1

    ds = load_dataset(Path(args.dataset))
    out = Path(args.out or DEFAULT_OUT[args.format])
    out.mkdir(parents=True, exist_ok=True)

    names = sorted(ds) if args.all else SUBSET_NAMES
    missing = [n for n in names if n not in ds]
    if missing:
        print(f"ERROR: dataset is missing problems: {missing}", file=sys.stderr)
        return 1

    for name in names:
        (out / f"{name}.lean").write_text(render(name, ds[name], args.format))
    print(f"Wrote {len(names)} {args.format} files to {out}/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
